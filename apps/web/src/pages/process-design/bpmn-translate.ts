const translate = (template: string, replacements?: Record<string, string>) =>
  (DICTIONARY[template] ?? template).replace(/{([^}]+)}/g, (_, key: string) => {
    const value = replacements?.[key] ?? `{${key}}`;
    return DICTIONARY[value] ?? value;
  });

export const vietnameseModule = { translate: ["value", translate] };
